export function shopUiString(lang: ShopContentLang, key: ShopUiKey, params?: Record<string, string | number>): string {
  const dict = SHOP_UI[lang] ?? SHOP_UI.en;
  const raw = dict[key] ?? SHOP_UI.en[key];
  return vars(raw, params);
}

export function shopWeekdayKey(day: string): ShopUiKey {
  const map: Record<string, ShopUiKey> = {
    mon: 'weekdayMon',
    tue: 'weekdayTue',
    wed: 'weekdayWed',
    thu: 'weekdayThu',
    fri: 'weekdayFri',
    sat: 'weekdaySat',
    sun: 'weekdaySun',
  };
  return map[day] ?? 'weekdayMon';
}
